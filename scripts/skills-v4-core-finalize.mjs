import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const OLD_SHA = 'e7a8dadd9adfb4115ddade8713a4eb1cd4378a77';
const FROZEN_SHA = 'f8cac893159959655d7787806704ce89d834d381';

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const writeJson = (path, value) => writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);

const source = readJson('.xtrm/specialists-source.json');
if (source.resolved_sha !== OLD_SHA && source.resolved_sha !== FROZEN_SHA) {
  throw new Error(`unexpected Specialists source pin: ${source.resolved_sha}`);
}
source.resolved_sha = FROZEN_SHA;
// vendor_manifest is regenerated by the canonical vendor script from exact Git blobs.
delete source.vendor_manifest;
writeJson('.xtrm/specialists-source.json', source);

const ownership = readJson('docs/skills-ownership.json');
if (ownership.release_source?.source_commit !== OLD_SHA && ownership.release_source?.source_commit !== FROZEN_SHA) {
  throw new Error(`unexpected ownership source pin: ${ownership.release_source?.source_commit}`);
}
ownership.release_source.source_commit = FROZEN_SHA;
writeJson('docs/skills-ownership.json', ownership);

const release = readJson('docs/skills-ownership.release.json');
if (release.mirrors?.specialists?.sha !== OLD_SHA && release.mirrors?.specialists?.sha !== FROZEN_SHA) {
  throw new Error(`unexpected release mirror pin: ${release.mirrors?.specialists?.sha}`);
}
release.mirrors.specialists.sha = FROZEN_SHA;
writeJson('docs/skills-ownership.release.json', release);

// Fail if a fourth tracked provenance surface still points at the superseded pin.
try {
  const stale = execFileSync('git', ['grep', '-n', OLD_SHA], { encoding: 'utf8' }).trim();
  if (stale) throw new Error(`stale Specialists SHA remains in tracked tree:\n${stale}`);
} catch (error) {
  if (error?.status !== 1) throw error; // git grep returns 1 when no matches exist.
}

console.log(`Core Specialists provenance pinned to ${FROZEN_SHA}`);
